-- Q01: Display customer name, city, customer segment, order ID, order date, and order status for every order placed in 2025.
SELECT 
    c.customer_name, 
    c.city, 
    c.customer_segment, 
    o.order_id, 
    o.order_date, 
    o.order_status
FROM Customers c
JOIN Orders o ON c.customer_id = o.customer_id
WHERE YEAR(o.order_date) = 2025;

-- Q02: Find all customers from Gujarat who belong to the Premium or Enterprise segment. Display customer name, city, and segment.
SELECT customer_name, city, customer_segment
FROM Customers
WHERE state = 'Gujarat' AND customer_segment IN ('Premium', 'Enterprise');

-- Q03: Display all products whose unit price is between ₹5,000 and ₹20,000, sorted from highest price to lowest price.
SELECT product_name, unit_price
FROM Products
WHERE unit_price BETWEEN 5000 AND 20000
ORDER BY unit_price DESC;

