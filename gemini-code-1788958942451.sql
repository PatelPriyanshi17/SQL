-- Q24: Find the product with the highest total quantity sold within each category. Do not use subqueries or window functions.
SELECT p1.category, p1.product_name, SUM(o1.quantity) AS total_quantity_sold
FROM Products p1
INNER JOIN Orders o1 ON p1.product_id = o1.product_id
GROUP BY p1.category, p1.product_id, p1.product_name
HAVING SUM(o1.quantity) >= ALL (
    SELECT SUM(o2.quantity)
    FROM Products p2
    INNER JOIN Orders o2 ON p2.product_id = o2.product_id
    WHERE p2.category = p1.category
    GROUP BY p2.product_id
);

