-- Q48: Create a report for each product showing product name, category, current stock, total quantity ordered, completed sales value, and number of distinct customers who ordered it. Products with no orders must also appear.
SELECT 
    p.product_name, 
    p.category, 
    p.stock_quantity AS current_stock, 
    ISNULL(SUM(o.quantity), 0) AS total_quantity_ordered, 
    ISNULL(SUM(CASE WHEN o.order_status = 'Completed' THEN o.quantity * p.unit_price ELSE 0 END), 0) AS completed_sales_value, 
    COUNT(DISTINCT o.customer_id) AS distinct_customers
FROM Products p
LEFT JOIN Orders o ON p.product_id = o.product_id
GROUP BY p.product_id, p.product_name, p.category, p.stock_quantity;

-- Q49: For each customer segment, compare completed-order revenue for pairs of customers in the same segment. Display the two customer names and their revenues only when the first customer's revenue is greater than the second customer's revenue.
SELECT 
    c1.customer_segment, 
    c1.customer_name AS customer_1, 
    rev1.revenue AS revenue_1, 
    c2.customer_name AS customer_2, 
    rev2.revenue AS revenue_2
FROM (
    SELECT o.customer_id, SUM(o.quantity * p.unit_price) AS revenue
    FROM Orders o 
    INNER JOIN Products p ON o.product_id = p.product_id
    WHERE o.order_status = 'Completed'
    GROUP BY o.customer_id
) rev1
INNER JOIN Customers c1 ON rev1.customer_id = c1.customer_id
INNER JOIN Customers c2 ON c1.customer_segment = c2.customer_segment AND c1.customer_id <> c2.customer_id
INNER JOIN (
    SELECT o.customer_id, SUM(o.quantity * p.unit_price) AS revenue
    FROM Orders o 
    INNER JOIN Products p ON o.product_id = p.product_id
    WHERE o.order_status = 'Completed'
    GROUP BY o.customer_id
) rev2 ON c2.customer_id = rev2.customer_id
WHERE rev1.revenue > rev2.revenue;

-- Q50: Build a management-level sales report showing customer segment, number of customers, number of completed orders, total quantity sold, total revenue, and average order value. Include segments even if a metric has no matching records.
SELECT 
    c.customer_segment, 
    COUNT(DISTINCT c.customer_id) AS total_customers, 
    COUNT(DISTINCT CASE WHEN o.order_status = 'Completed' THEN o.order_id END) AS completed_orders, 
    ISNULL(SUM(CASE WHEN o.order_status = 'Completed' THEN o.quantity ELSE 0 END), 0) AS total_quantity_sold, 
    ISNULL(SUM(CASE WHEN o.order_status = 'Completed' THEN o.quantity * p.unit_price ELSE 0 END), 0) AS total_revenue, 
    ISNULL(AVG(CASE WHEN o.order_status = 'Completed' THEN o.quantity * p.unit_price END), 0) AS avg_order_value
FROM Customers c
LEFT JOIN Orders o ON c.customer_id = o.customer_id
LEFT JOIN Products p ON o.product_id = p.product_id
GROUP BY c.customer_segment;